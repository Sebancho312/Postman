-- Expone solo horas libres, nunca los nombres o correos de otras reservas.
create or replace function public.horarios_disponibles(
    p_cancha_id bigint,
    p_fecha date,
    p_duracion_horas integer
)
returns table (hora_inicio text)
language sql
stable
security definer
set search_path = ''
as $function$
    select to_char(make_time(h.inicio, 0, 0), 'HH24:MI')
    from generate_series(8, 22 - p_duracion_horas) as h(inicio)
    where p_duracion_horas between 1 and 4
      and exists (select 1 from public.canchas c where c.id = p_cancha_id)
      and not exists (
          select 1 from public.reservas r
          where r.cancha_id = p_cancha_id
            and r.fecha = p_fecha
            and r.hora_inicio < make_time(h.inicio, 0, 0) + make_interval(hours => p_duracion_horas)
            and make_time(h.inicio, 0, 0) < r.hora_inicio + make_interval(hours => r.duracion_horas)
      )
    order by h.inicio;
$function$;

-- Inserta y revisa los cruces en una sola transacción.
create or replace function public.crear_reserva(
    p_cancha_id bigint,
    p_nombre text,
    p_correo text,
    p_fecha date,
    p_hora_inicio time,
    p_duracion_horas integer,
    p_numero_personas integer
)
returns table (
    id bigint,
    cancha_id bigint,
    nombre text,
    correo text,
    fecha date,
    hora_inicio time,
    duracion_horas integer,
    numero_personas integer,
    total numeric
)
language plpgsql
security definer
set search_path = ''
as $function$
declare
    v_cancha public.canchas%rowtype;
    v_reserva_id bigint;
begin
    if length(trim(coalesce(p_nombre, ''))) = 0
       or p_correo !~ '^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$' then
        raise exception 'Nombre y correo válidos son obligatorios' using errcode = '22023';
    end if;
    select * into v_cancha from public.canchas c where c.id = p_cancha_id for update;
    if not found then
        raise exception 'Cancha no encontrada' using errcode = 'P0002';
    end if;
    if p_fecha < current_date then
        raise exception 'La fecha no puede estar en el pasado' using errcode = '22023';
    end if;
    if p_duracion_horas not between 1 and 4 then
        raise exception 'La duración debe ser de 1 a 4 horas' using errcode = '22023';
    end if;
    if p_hora_inicio < time '08:00' or p_hora_inicio >= time '22:00'
       or p_hora_inicio + make_interval(hours => p_duracion_horas) > time '22:00' then
        raise exception 'El horario debe estar entre 08:00 y 22:00' using errcode = '22023';
    end if;
    if p_numero_personas not between 1 and v_cancha.capacidad then
        raise exception 'El número de personas supera la capacidad de la cancha' using errcode = '22023';
    end if;
    if exists (
        select 1 from public.reservas r
        where r.cancha_id = p_cancha_id and r.fecha = p_fecha
          and r.hora_inicio < p_hora_inicio + make_interval(hours => p_duracion_horas)
          and p_hora_inicio < r.hora_inicio + make_interval(hours => r.duracion_horas)
    ) then
        raise exception 'Ese horario ya está reservado para esta cancha' using errcode = '23P01';
    end if;

    insert into public.reservas (
        cancha_id, nombre, correo, fecha, hora_inicio, duracion_horas, numero_personas
    ) values (
        p_cancha_id, p_nombre, p_correo, p_fecha, p_hora_inicio, p_duracion_horas, p_numero_personas
    ) returning reservas.id into v_reserva_id;

    return query select v_reserva_id, p_cancha_id, p_nombre, p_correo, p_fecha,
        p_hora_inicio, p_duracion_horas, p_numero_personas,
        round(v_cancha.precio_por_hora * p_duracion_horas, 2);
end;
$function$;

revoke all on function public.horarios_disponibles(bigint, date, integer) from public;
revoke all on function public.crear_reserva(bigint, text, text, date, time, integer, integer) from public;
grant execute on function public.horarios_disponibles(bigint, date, integer) to anon;
grant execute on function public.crear_reserva(bigint, text, text, date, time, integer, integer) to anon;
