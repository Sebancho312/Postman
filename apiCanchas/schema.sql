create table if not exists public.canchas (
    id bigint generated by default as identity primary key,
    nombre text not null,
    deporte text not null,
    ubicacion text not null,
    capacidad integer not null check (capacidad > 0),
    precio_por_hora numeric(10, 2) not null check (precio_por_hora >= 0)
);

create table if not exists public.reservas (
    id bigint generated by default as identity primary key,
    cancha_id bigint not null references public.canchas(id) on delete restrict,
    nombre text not null,
    correo text not null,
    fecha date not null,
    hora_inicio time not null,
    duracion_horas integer not null check (duracion_horas between 1 and 4),
    numero_personas integer not null check (numero_personas > 0),
    created_at timestamptz not null default now()
);

